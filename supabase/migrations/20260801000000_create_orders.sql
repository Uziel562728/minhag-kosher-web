        item->>'product_name',
        item->>'product_brand',
        (item->>'unit_price')::numeric,
        (item->>'quantity')::integer,
        (item->>'subtotal')::numeric
    from jsonb_array_elements(p_items) as item;

    return query select v_order_id, v_order_number, p_total, v_created_at;
end;
