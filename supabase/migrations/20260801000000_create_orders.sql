        where o.idempotency_key = p_idempotency_key
        limit 1;
        
        if found then
            return query select v_existing_id, v_existing_order_number, v_existing_total, v_existing_created_at;
            return;
        end if;
    end if;

    -- Insert order
    insert into public.orders (
        customer_name,
        customer_phone,
        shipping_method,
        street,
        floor,
        department,
        customer_notes,
        idempotency_key,
        subtotal,
        total
    ) values (
        p_customer_name,
        p_customer_phone,
        p_shipping_method,
        p_street,
        p_floor,
        p_department,
        p_customer_notes,
        p_idempotency_key,
        p_subtotal,
        p_total
    )
    returning public.orders.id, public.orders.order_number, public.orders.created_at
    into v_order_id, v_order_number, v_created_at;

