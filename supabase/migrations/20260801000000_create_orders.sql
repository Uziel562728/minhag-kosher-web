-- 1. Create Orders Table
create table if not exists public.orders (
    id uuid primary key default gen_random_uuid(),
    order_number bigint generated by default as identity unique,
    customer_name text not null,
    customer_phone text not null,
    shipping_method text not null check (shipping_method in ('retiro', 'envio')),
    street text,
    floor text,
    department text,
    status text not null default 'pending' check (status in ('pending', 'confirmed', 'preparing', 'ready', 'delivered', 'cancelled')),
    subtotal numeric(12,2) not null check (subtotal >= 0),
    total numeric(12,2) not null check (total >= 0),
    customer_notes text,
    idempotency_key text unique,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- Constraint for street requirement when shipping_method = 'envio'
alter table public.orders drop constraint if exists check_shipping_street;
alter table public.orders add constraint check_shipping_street 
    check (shipping_method <> 'envio' or (street is not null and trim(street) <> ''));

-- 2. Create Order Items Table
create table if not exists public.order_items (
    id uuid primary key default gen_random_uuid(),
    order_id uuid not null references public.orders(id) on delete cascade,
    product_id uuid references public.products(id) on delete set null,
    product_name text not null,
    product_brand text,
    unit_price numeric(12,2) not null check (unit_price >= 0),
    quantity integer not null check (quantity > 0),
    subtotal numeric(12,2) not null check (subtotal >= 0),
    created_at timestamptz not null default now()
);

-- 3. Enable Row Level Security (RLS)
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

-- 4. Drop and Create Policies for authenticated admins
drop policy if exists "Allow authenticated admins to manage orders" on public.orders;
create policy "Allow authenticated admins to manage orders" on public.orders
    for all to authenticated using (true) with check (true);

drop policy if exists "Allow authenticated admins to manage order items" on public.order_items;
create policy "Allow authenticated admins to manage order items" on public.order_items
